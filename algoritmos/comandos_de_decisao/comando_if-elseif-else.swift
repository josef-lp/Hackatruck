var idadePessoa: Int = 20

if idadePessoa<=3{
    print("Um bebê de \(idadePessoa) anos")
}else if 3<idadePessoa && idadePessoa<=10{
    print("Uma criança de \(idadePessoa) anos")
}else if 11<=idadePessoa && idadePessoa<=17{
    print("Um adolescente de \(idadePessoa) anos")
}else{
print("Um adulto")
}